  // ---------- word helpers ----------
  const hasArt = w => w.pos === 'n' && (w.g === 'm' || w.g === 'f' || w.g === 'mf');
  function artHead(w) {          // the headword as a card shows it: with its article for nouns
    if (!hasArt(w)) return w.it;
    if (w.g === 'mf') { const m = M.defArt(w.it, 'm', 's'), f = M.defArt(w.it, 'f', 's'); return m === f ? M.withArt(m, w.it) : m + '/' + f + ' ' + w.it; }
    if (w.pltant) return M.withArt(M.defArt(w.it, w.g, 'p'), w.it);
    return M.withArt(M.defArt(w.it, w.g, 's'), w.it);
  }
  function heads(w) {            // typed answers accepted for English -> Italian
    const out = [w.it];
    if (hasArt(w)) {
      const gs = w.g === 'mf' ? ['m', 'f'] : [w.g];
      for (const g of gs) out.push(M.withArt(M.defArt(w.it, g, w.pltant ? 'p' : 's'), w.it));
    }
    if (w.alt) out.push(...[].concat(w.alt));
    return out;
  }
  function info(w) {
    if (w.pos === 'n') {
      if (w.g === 'mf') return 'noun, m./f.' + (w.pl && w.pl !== w.it ? ', pl. ' + w.pl : '');
      const g = w.g === 'f' ? 'f.' : 'm.';
      if (w.pltant) return 'noun, ' + g + ' pl. (plural only)';
      if (w.sg) return 'noun, ' + g + ' (usually no plural)';
      const p = D.plOf(w);
      if (p.pl === w.it) return 'noun, ' + g + ', invariable (pl. ' + M.withArt(M.defArt(w.it, p.g, 'p'), w.it) + ')';
      return 'noun, ' + g + ', pl. ' + M.withArt(M.defArt(p.pl, p.g, 'p'), p.pl) + (p.g !== w.g ? ' (' + p.g + '.)' : '') + (w.fem ? ' · female: ' + w.fem : '');
    }
    if (w.pos === 'adj' && w.forms) return 'adjective, ' + [...new Set(w.forms)].join(' / ');
    if (w.pos === 'v') return 'verb, ' + CONJ[w.conj] + (w.irr ? ', irregular' : '') + (w.refl ? ', usually reflexive' : '') + ' · aux. ' + ({ a: 'avere', e: 'essere', 'a/e': 'avere or essere' })[w.aux || 'a'];
    return POS[w.pos] || w.pos;
  }
  const verb = it => BYIT[it] && BYIT[it].pos === 'v' ? BYIT[it] : { it, conj: M.cls(it), aux: 'a' };
  const noun = (it, g) => BYIT[it] && BYIT[it].pos === 'n' ? BYIT[it] : { it, g };
  const adj = it => BYIT[it] && BYIT[it].forms ? BYIT[it] : { it, forms: M.adjForms({ it }) };

  // ---------- tables (all generated by the engine) ----------
  const SUBJ6 = ['io', 'tu', 'lui/lei', 'noi', 'voi', 'loro'];
  function verbTable(vs, tense, g, hl) {
    const V6 = vs.map(it => { const v = verb(it); return tense === 'pp' ? [0, 1, 2, 3, 4, 5].map(i => M.passato(v, i, g || 'm')) : M.tense(v, tense); });
    return `<div class="forms"><table><tr><th></th>${vs.map(x => `<th>${esc(x)}</th>`).join('')}</tr>${SUBJ6.map((p, i) => `<tr${hl === i ? ' class="hl"' : ''}><th>${p}</th>${V6.map(f => `<td>${esc(f[i])}</td>`).join('')}</tr>`).join('')}</table></div>`;
  }
  function nounTable(list) {
    return `<div class="forms"><table><tr><th>Singular</th><th>Plural</th></tr>${list.map(([it, g]) => {
      const n = noun(it, g), p = M.nounPlural(n);
      return `<tr><td>${esc(M.withArt(M.defArt(it, n.g, 's'), it))}</td><td>${esc(M.withArt(M.defArt(p.pl, p.g, 'p'), p.pl))}${p.g !== n.g ? ' <span class="muted">(' + p.g + '.)</span>' : ''}</td></tr>`; }).join('')}</table></div>`;
  }
  const ART_EX = [['before a consonant', 'libro', 'casa'], ['before s + consonant, z, gn, ps, x, y', 'studente', 'zia'], ['before a vowel', 'amico', 'amica']];
  function artTable() {
    return `<div class="forms"><table><tr><th></th><th>m. sing.</th><th>m. pl.</th><th>f. sing.</th><th>f. pl.</th></tr>${ART_EX.map(([l, m, f]) => {
      const mp = M.nounPlural({ it: m, g: 'm' }).pl, fp = M.nounPlural({ it: f, g: 'f' }).pl;
      return `<tr><th style="white-space:normal">${l}</th><td><b>${esc(M.defArt(m, 'm', 's'))}</b>${/'$/.test(M.defArt(m, 'm', 's')) ? '' : ' '}${esc(m)}</td><td><b>${esc(M.defArt(mp, 'm', 'p'))}</b> ${esc(mp)}</td><td><b>${esc(M.defArt(f, 'f', 's'))}</b>${/'$/.test(M.defArt(f, 'f', 's')) ? '' : ' '}${esc(f)}</td><td><b>le</b> ${esc(fp)}</td></tr>`; }).join('')}</table></div>`;
  }
  function indefTable() {
    return `<div class="forms"><table><tr><th></th><th>masculine</th><th>feminine</th></tr>${ART_EX.map(([l, m, f]) =>
      `<tr><th style="white-space:normal">${l}</th><td><b>${esc(M.indefArt(m, 'm'))}</b> ${esc(m)}</td><td><b>${esc(M.indefArt(f, 'f'))}</b>${/'$/.test(M.indefArt(f, 'f')) ? '' : ' '}${esc(f)}</td></tr>`).join('')}</table></div>`;
  }
  const ARTS7 = ['il', 'lo', "l'", 'la', 'i', 'gli', 'le'];
  const artPrep = (st, a) => a === 'il' ? st + 'l' : a === 'i' ? st + 'i' : a === 'gli' ? st + 'gli' : st + 'l' + a;
  function prepTable() {
    const P = [['di', 'de'], ['a', 'a'], ['da', 'da'], ['in', 'ne'], ['su', 'su']];
    return `<div class="forms"><table><tr><th></th>${ARTS7.map(a => `<th>${esc(a)}</th>`).join('')}</tr>${P.map(([p, st]) => `<tr><th>${p}</th>${ARTS7.map(a => `<td>${esc(artPrep(st, a))}</td>`).join('')}</tr>`).join('')}</table></div>`;
  }
  function adjTable(list) {
    return `<div class="forms"><table><tr><th></th><th>m. sing.</th><th>f. sing.</th><th>m. pl.</th><th>f. pl.</th></tr>${list.map(it => { const f = M.adjForms(adj(it)); return `<tr><th>${esc(it)}</th>${f.map(x => `<td>${esc(x)}</td>`).join('')}</tr>`; }).join('')}</table></div>`;
  }
  function ppTable(list) {
    const rows = list.map(it => { const v = verb(it); return [it, M.pastPart(v), ({ a: 'avere', e: 'essere', 'a/e': 'both' })[v.aux || 'a']]; });
    return `<div class="forms"><table><tr><th>Verb</th><th>Participle</th><th>Aux.</th></tr>${rows.map(r => `<tr><td>${esc(r[0])}</td><td><b>${esc(r[1])}</b></td><td>${r[2]}</td></tr>`).join('')}</table></div>`;
  }
  function rowsTable(t) {
    return `<div class="forms"><table><tr>${t.head.map(h => `<th>${esc(h)}</th>`).join('')}</tr>${t.rows.map(r => `<tr>${r.map(c => `<td>${esc(c)}</td>`).join('')}</tr>`).join('')}</table></div>`;
  }
  function table(t) {
    const h = t.title ? `<div class="csh">${esc(t.title)}</div>` : '';
    if (t.t === 'verbs') return h + verbTable(t.vs, t.tense, t.g);
    if (t.t === 'nouns') return h + nounTable(t.list);
    if (t.t === 'art') return h + artTable();
    if (t.t === 'indef') return '<div class="csh">Indefinite article</div>' + indefTable();
    if (t.t === 'prep') return '<div class="csh">Preposition + definite article</div>' + prepTable();
    if (t.t === 'adj') return h + adjTable(t.list);
    if (t.t === 'pp') return '<div class="csh">Common irregular participles</div>' + ppTable(t.list);
    if (t.t === 'rows') return h + rowsTable(t);
    return '';
  }

