  const POS = { n: 'noun', v: 'verb', adj: 'adjective', adv: 'adverb', prep: 'preposition', conj: 'conjunction', pron: 'pronoun', det: 'determiner', int: 'interjection', num: 'number', art: 'article' };
  const CONJ = { are: '-are', ere: '-ere', ire: '-ire', isc: '-ire (-isc-)' };
